PTS = [(262,1025),(300,948),(360,862),(440,786),(530,723),(630,673),(700,648),
       (738,668),(772,738),(810,828),(840,930),(853,1040),(858,1160),
       (840,1180),(780,1222),(700,1262),(600,1300),(500,1328),(400,1347),(300,1357),(272,1357),
       (262,1340),(262,1100)]
def spline(pts, n=10):
    out=[]; P=pts+pts[:3]; N=len(pts)
    for i in range(N):
        p0,p1,p2,p3=P[i-1] if i>0 else pts[-1],P[i],P[i+1],P[i+2]
        for k in range(n):
            t=k/n; t2=t*t; t3=t2*t
            x=0.5*((2*p1[0])+(-p0[0]+p2[0])*t+(2*p0[0]-5*p1[0]+4*p2[0]-p3[0])*t2+(-p0[0]+3*p1[0]-3*p2[0]+p3[0])*t3)
            y=0.5*((2*p1[1])+(-p0[1]+p2[1])*t+(2*p0[1]-5*p1[1]+4*p2[1]-p3[1])*t2+(-p0[1]+3*p1[1]-3*p2[1]+p3[1])*t3)
            out.append((x,y))
    return out
POLY = spline(PTS)
